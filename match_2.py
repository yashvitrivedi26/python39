#write a program to accept month number from user and display name of month using match case 

month = int(input("Enter Month Number:"))

match month:
    case 1:
        print('Winter')
    case 2:
        print('Winter')
    case 3:
        print('Spring')
    case 4:
        print('Spring')
    case 5:
        print('Summer')
    case 6:
        print('Summer')
    case 7:
        print('Monsoon')
    case 8:
        print('Monsoon')
    case 9:
        print('Monsoon')
    case 10:
        print('Autumn')
    case 11:
        print('Autumn')
    case 12:
        print('Winter')